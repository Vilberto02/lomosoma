"""Freeze the installed runtime dependency graph without adding test tooling."""
from importlib.metadata import distribution
from pathlib import Path
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

root = Path(__file__).resolve().parents[1]
pending = [Requirement(line) for line in (root / "requirements.in").read_text().splitlines() if line.strip() and not line.startswith("#")]
versions = {}
visited = set()
while pending:
    requirement = pending.pop()
    key = (canonicalize_name(requirement.name), tuple(sorted(requirement.extras)))
    if key in visited:
        continue
    visited.add(key)
    package = distribution(requirement.name)
    versions[canonicalize_name(package.metadata["Name"])] = package.version
    for raw in package.requires or []:
        dependency = Requirement(raw)
        if dependency.marker is None or any(dependency.marker.evaluate({"extra": extra}) for extra in (requirement.extras or {""})):
            pending.append(dependency)
(root / "requirements.txt").write_text("# Generated by backend/tools/lock_requirements.py; Python 3.14\n" + "\n".join(f"{name}=={version}" for name, version in sorted(versions.items())) + "\n", encoding="utf8")
